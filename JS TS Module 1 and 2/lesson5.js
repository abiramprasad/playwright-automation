let trafficLight="green";

if (trafficLight === 'red') {
    console.log('Stop');
} else if (trafficLight === 'yellow') {
    console.log('Caution');
} else if (trafficLight === 'green') {
    console.log('Go');
} else {
    console.log('Invalid traffic light color');
}

